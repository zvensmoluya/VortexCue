package io.github.zvensmoluya.vortexcue

import io.github.zvensmoluya.vortexcue.subtitle.*
import org.junit.Assert.assertEquals
import org.junit.Assert.assertThrows
import org.junit.Test

class WebVttParserTest {
    @Test
    fun `parses TransVortex bilingual output and cue settings`() {
        val content =
            """
            WEBVTT
            Kind: captions
            Language: und

            1
            00:00:00.000 --> 00:00:01.800 align:center position:50% line:90%
            Good evening.
            晚上好。

            2
            00:00:02.100 --> 00:00:05.400 align:center position:50% line:90%
            The 2026 timestamp.
            这是第二句。
            """.trimIndent()

        val cues = WebVttParser.parse(content)

        assertEquals(2, cues.size)
        assertEquals(0L, cues[0].startMs)
        assertEquals(1_800L, cues[0].endMs)
        assertEquals("Good evening.\n晚上好。", cues[0].text)
        assertEquals(2_100L, cues[1].startMs)
    }

    @Test
    fun `ignores notes and removes common markup`() {
        val content =
            """
            WEBVTT

            NOTE generated by test
            not a cue

            cue-id
            01:02.345 --> 01:04.000
            <v Speaker><i>Hello</i><br>world &amp; all</v>
            """.trimIndent()

        val cue = WebVttParser.parse(content).single()

        assertEquals(62_345L, cue.startMs)
        assertEquals("Hello\nworld & all", cue.text)
    }

    @Test
    fun `rejects invalid time ranges`() {
        val content = "WEBVTT\n\n00:02.000 --> 00:01.000\nBad"

        assertThrows(WebVttParseException::class.java) { WebVttParser.parse(content) }
    }
}
